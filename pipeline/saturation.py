"""Saturation: how the atlas grows as papers are added.

Re-derives the comparison (pipeline/subset_run.py) on growing subsets of the corpus: in the order the papers were
added (pilot, then batches 1-3, each batch in two halves), and in random orders (seeds 1..3) at the same sizes.
For each subset it records settings, results, cells, verdict cells (tight, log gap, poly gap, conflict) and tight
cells. The batch order is not random (each batch was chosen to cover what earlier ones missed), so the random orders
are the comparison for "what does the next random core paper add".

Writes data/reports/saturation.json and saturation.md. About 25 runs, 3 at a time (about 1 GB each).
Usage: uv run python pipeline/saturation.py [--workers 3] [--seeds 3]
"""

from __future__ import annotations

import argparse
import json
import random
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import subset_run  # noqa: E402

REP = subset_run.ROOT / "data" / "reports"
KEYS = ("papers", "settings", "settings_multi_paper", "results", "cells", "verdict_cells", "tight", "log_gap",
        "poly_gap", "conflict")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--workers", type=int, default=3)
    ap.add_argument("--seeds", type=int, default=3)
    args = ap.parse_args()
    b = subset_run.batches()
    rnd = random.Random(0)
    order = []  # batch order; within a batch, a fixed random order (split into halves)
    for k in sorted(set(b.values())):
        ids = sorted(p for p in b if b[p] == k)
        rnd.shuffle(ids)
        order.append(ids)
    sizes, cum = [], 0
    for i, ids in enumerate(order):
        if i > 0:
            sizes.append(cum + len(ids) // 2)
        cum += len(ids)
        sizes.append(cum)
    flat = [p for ids in order for p in ids]
    orders = {"batch": flat}
    for s in range(1, args.seeds + 1):
        o = sorted(b)
        random.Random(s).shuffle(o)
        orders[f"random{s}"] = o
    jobs = [(name, n) for name in orders for n in sizes if n < len(flat) or name == "batch"]
    with ThreadPoolExecutor(max_workers=args.workers) as ex:
        res = list(ex.map(lambda j: subset_run.run(papers=set(orders[j[0]][:j[1]])), jobs))
    full = next(r for (name, n), r in zip(jobs, res) if name == "batch" and n == len(flat))
    rows = []
    for (name, n), r in zip(jobs, res):
        rows.append({"order": name, "n": n, **{k: r[k] for k in KEYS}})
    for name in orders:
        if name != "batch":
            rows.append({"order": name, "n": len(flat), **{k: full[k] for k in KEYS}})
    rows.sort(key=lambda r: (r["order"], r["n"]))
    (REP / "saturation.json").write_text(json.dumps({"sizes": sizes, "batch_sizes": [len(o) for o in order],
                                                     "rows": rows}, indent=1))
    lines = ["# Saturation", "",
             "Generated by `pipeline/saturation.py`: the comparison re-derived on growing subsets of the corpus, in the "
             "order papers were added (`batch`: pilot, then batches 1–3, each in two halves) and in random orders.", "",
             "| order | papers | settings | settings with >1 paper | results | cells | verdict cells | tight | log gap "
             "| poly gap | conflict |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['order']} | {r['n']} | " + " | ".join(str(r[k]) for k in KEYS[1:]) + " |")
    (REP / "saturation.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()

"""Phase 3 exit check: are the pilot facts rediscovered from extracted data alone?

For each fact in data/ground_truth/pilot-facts.yaml:
  - find canonical settings matching the fact's setting (objective, feedback,
    environment, action space, context; noise is ignored because papers state
    different reward models for the same problem);
  - pick the comparison cell for the fact's regime (quantity family x dependence);
  - check the tightness status against the expected one, and the best upper /
    lower rates against the fact's own bounds (profiled with compare.py).

Verdicts: PASS (status and rates agree), PASS_STATUS (status agrees, the best rates
found differ from the fact's, e.g. a weaker upper bound), PARTIAL (some evidence, e.g. the right
upper rate but no lower bound yet), FAIL (data contradicts the fact), MISSING (no
matching setting / no bounds), MANUAL (algorithm-specific or impossibility facts,
not machine-checkable yet).

Writes data/acceptance-report.md.
Usage: uv run python pipeline/acceptance.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import compare  # noqa: E402
import schema  # noqa: E402

ROOT = schema.ROOT
CAN = ROOT / "data" / "canonical"
FACTS = ROOT / "data" / "ground_truth" / "pilot-facts.yaml"
REPORT = ROOT / "data" / "acceptance-report.md"
MATCH_DIMS = ("objective", "feedback", "environment", "action_space", "context")
EXPECTED = {"tight_constants": {"tight"}, "tight_logs": {"tight", "log_gap"}, "log_gap": {"log_gap", "tight"},
            "poly_gap": {"poly_gap"}}
STATUS_RANK = {"tight": 0, "log_gap": 1, "poly_gap": 2, "no_lower": 3, "no_upper": 4, "conflict": 5}


def regime_of(fact: dict) -> tuple[str, str]:
    r = fact.get("regime", "").lower()
    fam = "hp_regret" if "high probability" in r else "regret"
    dep = "instance_dependent" if ("instance" in r or "asymptotic" in r) else "worst_case"
    return fam, dep


def fact_rates(fact: dict, canonical: set) -> dict:
    out = {}
    for side in ("upper", "lower"):
        b = (fact.get(side) or {}).get("bound")
        if b:
            p = compare.profile(compare.instance_expr(b, (fact[side].get("notation") or "O")), canonical)
            if p:
                out[side] = {v: compare.fmt(ab) for v, ab in p.items() if not v.startswith("_")}
    return out


def main() -> None:
    facts = yaml.safe_load(FACTS.read_text())["facts"]
    settings = json.loads((CAN / "settings.json").read_text())
    cmp = json.loads((CAN / "comparison.json").read_text())["settings"]
    canonical = set(schema.load_variables()["variables"]) | {"Delta"}
    lines = ["# Acceptance report (pilot facts)", "",
             "Generated by `pipeline/acceptance.py` from `data/canonical/comparison.json`. Rates are growth exponents "
             "per variable (`0.5·log^1` = v^0.5 log v); K, d, 1/Δ are measured in the regime T large.", ""]
    tally = {}
    for f in facts:
        exp = f.get("status")
        if not isinstance(f.get("setting"), dict) or exp not in EXPECTED or f.get("check") == "manual":
            verdict, detail = "MANUAL", f"status `{exp}` is not machine-checkable yet"
        else:
            fam, dep = regime_of(f)
            want = {d: f["setting"].get(d) for d in MATCH_DIMS}
            required = {d: set(f["setting"].get(d) or []) for d in ("learner_knows", "instance_assumptions")}
            matches = [s for s in settings if all(s["key"].get(d) == v for d, v in want.items())
                       and all(req <= set(s["key"].get(d) or []) for d, req in required.items())]
            cells = [(s, cmp.get(s["id"], {}).get(f"{fam}|{dep}")) for s in matches]
            cells = [(s, c) for s, c in cells if c]
            if not cells:
                verdict, detail = "MISSING", f"{len(matches)} matching settings, none with `{fam}|{dep}` bounds"
            else:
                s, c = min(cells, key=lambda sc: (STATUS_RANK[sc[1]["status"]], -sc[1]["n_upper"] - sc[1]["n_lower"]))
                rates = fact_rates(f, canonical)
                got_u = {v: pv["upper"] for v, pv in c["per_var"].items()}
                got_l = {v: pv["lower"] for v, pv in c["per_var"].items()}
                rate_ok = all(got_u.get(v) == r for v, r in rates.get("upper", {}).items()) and \
                          all(got_l.get(v) == r for v, r in rates.get("lower", {}).items())
                if c["status"] in EXPECTED[exp] and rate_ok:
                    verdict = "PASS"
                elif c["status"] in EXPECTED[exp]:
                    verdict = "PASS_STATUS"  # right tightness status, different (usually weaker) rates
                elif c["status"] in ("no_lower", "no_upper"):
                    verdict = "PARTIAL"
                elif c["status"] == "conflict" or STATUS_RANK[c["status"]] < min(STATUS_RANK[x] for x in EXPECTED[exp]):
                    verdict = "FAIL"
                else:
                    verdict = "PARTIAL"
                detail = (f"best of {len(cells)} matching settings: [{s['label']}](../site) `{s['id']}` → **{c['status']}**; "
                          f"per variable: " + ", ".join(f"{v}: up {pv['upper']} / low {pv['lower']} ({pv['status']})"
                                                        for v, pv in c["per_var"].items())
                          + (f"; expected rates {rates}" if rates else ""))
        tally[verdict] = tally.get(verdict, 0) + 1
        lines.append(f"- **{f['id']}** ({f.get('regime')}) expected `{exp}` → **{verdict}**. {detail}")
    summary = ", ".join(f"{k} {v}" for k, v in sorted(tally.items()))
    lines[4:4] = [f"**Summary:** {summary}", ""]
    REPORT.write_text("\n".join(lines) + "\n")
    print(summary)


if __name__ == "__main__":
    main()

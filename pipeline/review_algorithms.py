"""Review the algorithm registry (data/algorithms.yaml) against the extractions.

The registry was seeded by an LLM from the pilot. Each extraction now records, per algorithm,
its `registry_id` (or null) and `is_new` (the paper introduces it), which is evidence:

  introduced_in   compared with the papers that mark the algorithm as new: missing (null but
                  exactly one paper introduces it), contradicted (another paper introduces it
                  and ours does not), or ambiguous (several papers claim it)
  aliases         an alias shared by two entries
  unused          no extraction refers to the entry
  candidates      unregistered algorithm names used by >= 3 papers (normalised), with the
                  paper that introduces them if one says so: proposals for new entries

Writes data/reports/algorithm-registry-review.md. With --apply, fills `introduced_in` where it
is null and exactly one corpus paper introduces the algorithm (recorded in a `review` note).
Usage: uv run python pipeline/review_algorithms.py [--apply]
"""

from __future__ import annotations

import argparse
import collections
import json
import re
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import schema  # noqa: E402

ROOT = schema.ROOT
REG = ROOT / "data" / "algorithms.yaml"


def norm(name: str) -> str:
    """Case, spaces and punctuation are ignored; +, *, primes and Greek letters are kept (KL-UCB vs KL-UCB++)."""
    return re.sub(r"[\s\-_.,;:()\[\]{}/'\"]+", "", (name or "").lower())


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    args = ap.parse_args()
    reg = yaml.safe_load(REG.read_text())
    algos = {a["id"]: a for a in reg["algorithms"]}
    manifest = {p["id"]: p for p in yaml.safe_load((ROOT / "corpus" / "manifest.yaml").read_text())["papers"]}
    year = lambda pid: (manifest.get(pid) or {}).get("year") or 9999

    uses = collections.defaultdict(list)       # registry id -> [(paper, name, is_new)]
    unreg = collections.defaultdict(list)      # normalised name -> [(paper, name, is_new)]
    for f in sorted((ROOT / "data" / "extractions").glob("*.json")):
        for a in json.loads(f.read_text()).get("algorithms") or []:
            rec = (f.stem, a["name"], bool(a.get("is_new")))
            if a.get("registry_id") in algos:
                uses[a["registry_id"]].append(rec)
            elif a.get("name"):
                unreg[norm(a["name"])].append(rec)

    missing, contradicted, ambiguous, unused, applied = [], [], [], [], []
    for aid, a in algos.items():
        u = uses.get(aid, [])
        if not u:
            unused.append(aid)
            continue
        new = sorted({p for p, _, n in u if n}, key=year)
        intro = a.get("introduced_in")
        if not intro and len(new) == 1:
            missing.append((aid, new[0]))
            if args.apply:
                a["introduced_in"] = new[0]
                a["review"] = f"introduced_in filled 2026-10-23 by pipeline/review_algorithms.py: the only corpus paper marking it new"
                applied.append(aid)
        elif not intro and len(new) > 1:
            ambiguous.append((aid, new))
        elif intro and new and intro not in new:
            contradicted.append((aid, intro, new))

    alias_owner = collections.defaultdict(set)
    for aid, a in algos.items():
        for x in [a["name"], *(a.get("aliases") or [])]:
            alias_owner[norm(x)].add(aid)
    clashes = {k: sorted(v) for k, v in alias_owner.items() if len(v) > 1 and k}

    cands = []
    for k, recs in unreg.items():
        papers = sorted({p for p, _, _ in recs})
        if len(papers) >= 3:
            intro = sorted({p for p, _, n in recs if n}, key=year)
            cands.append((len(papers), recs[0][1], papers, intro))
    cands.sort(key=lambda c: -c[0])

    if args.apply and applied:
        REG.write_text("# Algorithm registry (D13). Seeded by pipeline/seed_algorithms.py from the v0.2\n"
                       "# extractions; review by hand. `id`s are stable: rename via aliases, never reuse.\n"
                       "# introduced_in partly filled from extraction evidence (pipeline/review_algorithms.py).\n"
                       + yaml.safe_dump(reg, sort_keys=False, allow_unicode=True, width=110))

    L = ["# Algorithm registry review", "",
         "Generated by `pipeline/review_algorithms.py` from the 558 extractions (each algorithm a paper uses records its "
         "registry id and whether the paper introduces it). The registry was seeded by an LLM and is not human-verified.", "",
         f"- entries: {len(algos)}; used by at least one extraction: {len(algos) - len(unused)}; unused: {len(unused)}",
         f"- `introduced_in` missing but one corpus paper introduces it: {len(missing)}"
         + (f" (filled: {len(applied)})" if applied else ""),
         f"- `introduced_in` contradicted (another corpus paper marks it new, ours does not): {len(contradicted)}",
         f"- several corpus papers claim to introduce it: {len(ambiguous)}",
         f"- aliases shared by two entries: {len(clashes)}",
         f"- unregistered names used by ≥ 3 papers (proposals): {len(cands)}", "",
         "## Contradicted `introduced_in`", "", "| id | registry says | corpus papers marking it new |", "|---|---|---|"]
    L += [f"| {aid} | {intro} | {', '.join(new)} |" for aid, intro, new in contradicted] or ["| – | | |"]
    L += ["", "## Several papers claim to introduce it", "", "| id | papers (by year) |", "|---|---|"]
    L += [f"| {aid} | {', '.join(new)} |" for aid, new in ambiguous] or ["| – | |"]
    L += ["", "## Shared aliases", ""] + ([f"- `{k}`: {', '.join(v)}" for k, v in clashes.items()] or ["None."])
    L += ["", "## Proposed new entries (unregistered, ≥ 3 papers)", "", "| name | papers | introduced by (per extraction) |",
          "|---|---|---|"]
    L += [f"| {name} | {n}: {', '.join(p[:4])}{'…' if n > 4 else ''} | {', '.join(i) or '–'} |" for n, name, p, i in cands[:60]]
    L += ["", "## Unused entries", "", ", ".join(unused) or "None."]
    (ROOT / "data" / "reports" / "algorithm-registry-review.md").write_text("\n".join(L) + "\n")
    print(f"{len(algos)} entries; unused {len(unused)}; missing intro {len(missing)} (applied {len(applied)}); "
          f"contradicted {len(contradicted)}; ambiguous {len(ambiguous)}; alias clashes {len(clashes)}; proposals {len(cands)}")


if __name__ == "__main__":
    main()

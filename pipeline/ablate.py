"""Ablation of the comparison semantics: switch off one rule at a time and count what changes.

Each rule exists because, without it, the atlas reports something false. Mostly that is a conflict (an upper bound
below a lower bound in the same cell); some rules instead stop a false "tight". Re-deriving the comparison with the
rule off measures what it does on the current corpus. Every run uses a copy of the repo (pipeline/subset_run.py).

Writes data/reports/ablations.json and ablations.md. Takes about half an hour (3 runs at a time, about 1 GB each).
Usage: uv run python pipeline/ablate.py [--workers 3]
"""

from __future__ import annotations

import argparse
import json
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import subset_run  # noqa: E402

REP = subset_run.ROOT / "data" / "reports"
# (name, layer, what the rule does). Names are the ATLAS_ABLATE switches in resolve.py, order.py and compare.py.
RULES = [
    ("corrections", "data", "reviewed corrections on top of the extractions (a dropped condition, a misread expression)"),
    ("scope_classes", "data", "drop settings whose defining feature is out of scope (multi-agent, state-dependent, ...)"),
    ("field_patches", "data", "fields added in ontology 0.7–0.8, filled from the extracted text"),
    ("exact_fields", "order", "fields whose unstated value matches no stated one (dueling winner, market mechanism)"),
    ("comparator_family", "comparison", "regret against a different benchmark (switching, dynamic, foresight) is its own family"),
    ("adaptive_split", "comparison", "against adaptive adversaries, pseudo- and expected regret are not pooled"),
    ("data_dependent", "comparison", "small-loss and variation bounds form their own regime"),
    ("side_conditions", "comparison", "a condition fixing a scanned variable (K = 2, d treated as constant) hides its exponent"),
    ("hidden_instance_constant", "comparison", "an instance-dependent O(.) bound without a gap hides a gap-dependent constant"),
    ("model_change", "comparison", "a condition that changes the protocol (quantum oracle, extra feedback) removes the bound"),
    ("instance_restriction", "comparison", "an upper bound for a restricted instance class does not set the rate"),
    ("t_capped", "comparison", "an upper bound valid only for small horizons does not set the rate"),
    ("algorithm_class", "comparison", "lower bounds for one algorithm or class (not all / consistent) do not set the rate"),
    ("growing_parameter", "comparison", "a lower bound needing a parameter that grows with T does not set the rate"),
    ("held_unresolved", "comparison", "a violation resting on held instance parameters gets no verdict"),
    ("hidden_logs", "comparison", "equal polynomial rates stated with O~ / Omega~ are a log gap, not tight"),
]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--workers", type=int, default=3)
    args = ap.parse_args()
    jobs = [("baseline", ())] + [(r[0], (r[0],)) for r in RULES] + [("all", tuple(r[0] for r in RULES))]
    with ThreadPoolExecutor(max_workers=args.workers) as ex:
        runs = dict(zip([j[0] for j in jobs], ex.map(lambda j: subset_run.run(ablate=j[1]), jobs)))
    base = runs["baseline"]
    out = {"baseline": {k: v for k, v in base.items() if k != "status"}, "rules": []}
    for name, layer, what in RULES + [("all", "all", "every rule above switched off at once")]:
        r = runs[name]
        common = set(base["status"]) & set(r["status"])
        new_conf = sorted(set(r["conflicts"]) - set(base["conflicts"]))
        out["rules"].append({
            "rule": name, "layer": layer, "what": what,
            **{k: r[k] for k in ("cells", "verdict_cells", "tight", "log_gap", "poly_gap", "conflict", "settings")},
            "changed": sum(1 for c in common if base["status"][c] != r["status"][c]),
            "to_tight": sum(1 for c in common if r["status"][c] == "tight" and base["status"][c] != "tight"),
            "from_tight": sum(1 for c in common if base["status"][c] == "tight" and r["status"][c] != "tight"),
            "new_conflicts": new_conf})
    (REP / "ablations.json").write_text(json.dumps(out, indent=1))
    b = out["baseline"]
    lines = ["# Ablation of the comparison semantics", "",
             "Generated by `pipeline/ablate.py`: the comparison re-derived with one rule switched off at a time, on "
             "the whole corpus. *Conflict cells* would be reported as contradictions in the literature; "
             "*→ tight* counts cells that would wrongly or newly read as tight; *changed* counts cells (present in "
             "both runs) whose status differs.", "",
             f"Baseline: {b['cells']} cells, {b['tight']} tight, {b['log_gap']} log gap, {b['poly_gap']} poly gap, "
             f"{b['conflict']} conflict.", "",
             "| rule | layer | what it does | cells | tight | conflict cells | → tight | tight → other | changed |",
             "|---|---|---|---|---|---|---|---|---|"]
    for r in out["rules"]:
        lines.append(f"| `{r['rule']}` | {r['layer']} | {r['what']} | {r['cells']} | {r['tight']} | {r['conflict']} | "
                     f"{r['to_tight']} | {r['from_tight']} | {r['changed']} |")
    lines += ["", "## New conflict cells per rule (first 8)", ""]
    for r in out["rules"]:
        if r["new_conflicts"]:
            lines.append(f"- `{r['rule']}` ({len(r['new_conflicts'])}): " + ", ".join(f"`{c}`" for c in r["new_conflicts"][:8]))
    (REP / "ablations.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[:len(RULES) + 8]))


if __name__ == "__main__":
    main()
